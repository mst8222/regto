-- api_keys：AI/CI 长期凭据。明文只在创建响应中出现一次，库中仅存 sha256（DEC-03）。
CREATE TABLE IF NOT EXISTS api_keys (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_prefix    VARCHAR(12) NOT NULL,           -- 明文前缀，用于列表展示与定位
  key_hash      CHAR(64) NOT NULL,             -- sha256(明文)
  name          VARCHAR(64) NOT NULL,
  subject_kind  VARCHAR(10) NOT NULL,          -- human | ai | system
  subject_id    BIGINT NOT NULL,               -- 绑定用户（人类主体）
  agent_id      VARCHAR(64) NULL,              -- AI 主体标识；人类 key 为空
  scopes        JSONB NOT NULL DEFAULT '[]',
  status        VARCHAR(10) NOT NULL DEFAULT 'active',  -- active | revoked
  expires_at    TIMESTAMPTZ(3) NULL,
  last_used_at  TIMESTAMPTZ(3) NULL,
  created_by_id BIGINT NULL,
  created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  revoked_at    TIMESTAMPTZ(3) NULL,
  CONSTRAINT uniq_api_key_hash UNIQUE (key_hash)
);
CREATE INDEX IF NOT EXISTS idx_api_keys_prefix ON api_keys (key_prefix);
CREATE INDEX IF NOT EXISTS idx_api_keys_active ON api_keys (key_hash) WHERE status = 'active';

-- refresh_tokens：一次性刷新令牌，只存哈希；重放时按 family_id 连坐撤销（DEC-04）。
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash CHAR(64) NOT NULL,
  user_id    BIGINT NOT NULL REFERENCES users (id),
  family_id  VARCHAR(26) NOT NULL,             -- ULID：撤销的最小单位
  expires_at TIMESTAMPTZ(3) NOT NULL,
  used_at    TIMESTAMPTZ(3) NULL,              -- 非空 = 已使用（一次性）
  revoked_at TIMESTAMPTZ(3) NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family ON refresh_tokens (family_id);

