-- 范围：项目域——projects（**单表多类型**）+ project_products
-- 依据：ROADMAP §3.3 映射表「项目域 5」与建模红线（ADR-0002）
-- 红线：projects 必须单表多类型！API 层 sprints 只是 kind='sprint' 的投影。
--       拆表会导致父子 path/grade、project_stories、统计全面失真。
-- 语义对齐禅道：zt_project 以 type 区分 program/project/sprint/stage/kanban，
--       自关联 project 字段 + grade/path 表达层级（ROADMAP §2 调研结论）。
-- 方言：PostgreSQL（本机 WSL2）。合入 main 后禁止修改。

CREATE TABLE IF NOT EXISTS projects (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind          VARCHAR(16) NOT NULL,              -- program|project|sprint|stage
  parent_id     BIGINT NULL REFERENCES projects(id),
  path          VARCHAR(1024) NOT NULL DEFAULT '', -- 逗号分隔祖先链
  grade         SMALLINT NOT NULL DEFAULT 1,
  name          VARCHAR(255) NOT NULL,
  code          VARCHAR(64) NULL,                  -- 项目短码（可空，非唯一约束由应用保证）
  status        VARCHAR(20) NOT NULL DEFAULT 'wait', -- wait/doing/suspended/closed/delay
  pm_id         BIGINT NULL,                       -- 负责人 → users.id
  description   TEXT NULL,
  begin_date    DATE NULL,
  end_date      DATE NULL,
  opened_by_id  BIGINT NOT NULL,
  opened_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  closed_by_id  BIGINT NULL,
  closed_at     TIMESTAMPTZ(3) NULL,
  created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ(3) NULL,
  CONSTRAINT chk_projects_kind CHECK (kind IN ('program','project','sprint','stage')),
  CONSTRAINT chk_projects_status CHECK (status IN ('wait','doing','suspended','closed','delay'))
);
CREATE INDEX IF NOT EXISTS idx_projects_kind_status ON projects (kind, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_projects_parent ON projects (parent_id) WHERE deleted_at IS NULL;

-- project_products：项目/迭代 ↔ 产品 多对多（禅道 zt_projectproduct）
CREATE TABLE IF NOT EXISTS project_products (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES projects(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_project_product UNIQUE (project_id, product_id)
);
