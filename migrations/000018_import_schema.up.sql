-- ============================================================
-- 0. 记账 schema（与业务 schema 隔离：导入器元数据不属于业务数据）
-- ============================================================
CREATE SCHEMA IF NOT EXISTS regto_import;

-- ============================================================
-- 1. import_runs：一次导入的记账与断点（REQ-04）
-- ============================================================
CREATE TABLE IF NOT EXISTS regto_import.import_runs (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key             VARCHAR(64) NOT NULL UNIQUE,     -- 幂等键（用户指定或时间生成）
  source_fingerprint  VARCHAR(64) NOT NULL DEFAULT '', -- 源库指纹：库名+表清单 sha256（防跨库续跑）
  phase               VARCHAR(8) NOT NULL DEFAULT 's1',  -- s1|s2|done
  table_name          VARCHAR(64) NOT NULL DEFAULT '', -- 当前表（断点定位）
  cursor_last_id      BIGINT NOT NULL DEFAULT 0,       -- 该表已处理到的最大源 ID（REQ-01）
  status              VARCHAR(16) NOT NULL DEFAULT 'running', -- running|done|failed
  total_read          BIGINT NOT NULL DEFAULT 0,
  total_written       BIGINT NOT NULL DEFAULT 0,
  total_skipped       BIGINT NOT NULL DEFAULT 0,
  total_errors        BIGINT NOT NULL DEFAULT 0,
  started_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  finished_at         TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_import_runs_status ON regto_import.import_runs (status, started_at DESC);

-- ============================================================
-- 2. import_id_map：源 ID → 目标 ID 映射（幂等判定，REQ-04）
-- ============================================================
CREATE TABLE IF NOT EXISTS regto_import.import_id_map (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key     VARCHAR(64) NOT NULL,
  table_name  VARCHAR(64) NOT NULL,
  source_id   BIGINT NOT NULL,
  target_id   BIGINT NOT NULL,
  created_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_id_map
    ON regto_import.import_id_map (run_key, table_name, source_id);   -- 同源 ID 只映射一次
CREATE INDEX IF NOT EXISTS idx_id_map_target
    ON regto_import.import_id_map (table_name, target_id);           -- 反查：目标 ID → 源 ID

-- ============================================================
-- 3. import_errors：单行失败账本（REQ-05）
-- ============================================================
CREATE TABLE IF NOT EXISTS regto_import.import_errors (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_key        VARCHAR(64) NOT NULL,
  phase          VARCHAR(8) NOT NULL,
  table_name     VARCHAR(64) NOT NULL,
  source_id      BIGINT NOT NULL DEFAULT 0,
  error_code     VARCHAR(64) NOT NULL,
  error_message  TEXT NOT NULL DEFAULT '',
  payload        JSONB NULL,      -- 原始行快照（便于重放/诊断）
  created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_import_errors_run ON regto_import.import_errors (run_key, table_name);

-- ============================================================
-- 4. 应用账号授权（记账三表：SELECT/INSERT/UPDATE——游标需要 UPDATE）
-- ============================================================
DO $$
DECLARE
    tbl text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'regto_app') THEN
        RAISE NOTICE '角色 regto_app 不存在，跳过授权（请先执行 docs/deploy/01-init-database.sql）';
        RETURN;
    END IF;

    EXECUTE 'REVOKE ALL ON SCHEMA regto_import FROM regto_app';
    EXECUTE 'GRANT USAGE ON SCHEMA regto_import TO regto_app';
    FOR tbl IN
        SELECT unnest(ARRAY['import_runs', 'import_id_map', 'import_errors'])
    LOOP
        EXECUTE format('REVOKE ALL ON regto_import.%I FROM regto_app', tbl);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON regto_import.%I TO regto_app', tbl);
        RAISE NOTICE '已授权 regto_app: regto_import.%', tbl;
    END LOOP;
END
$$;

