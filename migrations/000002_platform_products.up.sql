-- 范围：产品域——products / branches / modules（统一模块树，type 区分 story/bug/case/task/doc）
-- 依据：ROADMAP §3.3 映射表「产品域 3」
-- 说明：zt_product 的 30+ 冗余统计列全部删除，按需聚合（ROADMAP 命名差异表）。
-- 方言：PostgreSQL（本机 WSL2）。合入 main 后禁止修改。

CREATE TABLE IF NOT EXISTS products (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(255) NOT NULL,
  code         VARCHAR(64) NOT NULL,             -- 产品短码，唯一
  description  TEXT NULL,
  owner_id     BIGINT NULL,                      -- 产品负责人 → users.id
  created_by_id BIGINT NOT NULL,
  created_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at   TIMESTAMPTZ(3) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_products_code ON products (code) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_products_owner ON products (owner_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS branches (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  name       VARCHAR(255) NOT NULL,
  status     VARCHAR(20) NOT NULL DEFAULT 'active',  -- active/closed
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_branches_product ON branches (product_id) WHERE deleted_at IS NULL;

-- modules：通用模块树（禅道 zt_module 语义：靠 type 区分归属对象）
CREATE TABLE IF NOT EXISTS modules (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type       VARCHAR(20) NOT NULL,               -- story/bug/case/task/doc
  parent_id  BIGINT NULL REFERENCES modules(id),
  path       VARCHAR(1024) NOT NULL DEFAULT '',  -- 逗号分隔的祖先链，如 ",1,5,9,"
  grade      SMALLINT NOT NULL DEFAULT 1,
  name       VARCHAR(255) NOT NULL,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  owner_id   BIGINT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_modules_type_parent ON modules (type, parent_id) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uniq_modules_type_parent_name ON modules (type, parent_id, name) WHERE deleted_at IS NULL;
