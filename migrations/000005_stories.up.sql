-- stories：需求主表（M1 字段子集）
CREATE TABLE IF NOT EXISTS stories (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id        BIGINT NOT NULL,
  module_id         BIGINT NULL,
  title             VARCHAR(255) NOT NULL,
  type              VARCHAR(20) NOT NULL DEFAULT 'story',
  pri               SMALLINT NOT NULL DEFAULT 3,
  estimate          NUMERIC(10,2) NULL,
  status            VARCHAR(20) NOT NULL,
  stage             VARCHAR(20) NOT NULL DEFAULT 'wait',
  spec_version      INTEGER NOT NULL DEFAULT 1,
  closed_reason     VARCHAR(20) NULL,
  reviewers         JSONB NULL,
  source_note       VARCHAR(255) NULL,
  opened_by_id      BIGINT NOT NULL,
  opened_at         TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  assigned_to_id    BIGINT NULL,
  assigned_at       TIMESTAMPTZ(3) NULL,
  last_edited_by_id BIGINT NULL,
  last_edited_at    TIMESTAMPTZ(3) NULL,
  changed_by_id     BIGINT NULL,
  closed_by_id      BIGINT NULL,
  closed_at         TIMESTAMPTZ(3) NULL,
  deleted_at        TIMESTAMPTZ(3) NULL,
  created_at        TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_stories_product_status ON stories (product_id, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_stories_stage ON stories (stage) WHERE deleted_at IS NULL;

-- story_specs：版本化规格，UNIQUE(story_id, version)，旧版本不可变
CREATE TABLE IF NOT EXISTS story_specs (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id       BIGINT NOT NULL REFERENCES stories(id),
  version        INTEGER NOT NULL,
  title          VARCHAR(255) NOT NULL,
  spec           TEXT NULL,
  verify         TEXT NULL,
  pri            SMALLINT NOT NULL DEFAULT 3,
  estimate       NUMERIC(10,2) NULL,
  created_by_id  BIGINT NOT NULL,
  created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_story_version UNIQUE (story_id, version)
);

-- story_reviews：评审记录
CREATE TABLE IF NOT EXISTS story_reviews (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id     BIGINT NOT NULL REFERENCES stories(id),
  version      INTEGER NOT NULL,
  reviewer_id  BIGINT NOT NULL,
  result       VARCHAR(10) NOT NULL,
  comment      VARCHAR(1000) NULL,
  reviewed_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_story_reviews_story_version ON story_reviews (story_id, version);
