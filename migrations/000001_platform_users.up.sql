CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account       VARCHAR(64) NOT NULL,            -- 登录名；禅道 account 语义保留
  password_hash VARCHAR(255) NOT NULL,           -- bcrypt；禅道 md5 导入时强制重置
  realname      VARCHAR(64) NOT NULL DEFAULT '',
  email         VARCHAR(255) NULL,
  mobile        VARCHAR(32) NULL,
  avatar        VARCHAR(512) NULL,
  disabled      BOOLEAN NOT NULL DEFAULT false,
  last_login_at TIMESTAMPTZ(3) NULL,
  created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ(3) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_users_account ON users (account) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_users_disabled ON users (disabled) WHERE deleted_at IS NULL;
