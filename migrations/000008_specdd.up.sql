-- spec_documents：文档级索引，file_path 为唯一键（Git 是唯一真源）。
CREATE TABLE IF NOT EXISTS spec_documents (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id        VARCHAR(64) NOT NULL,
  doc_type      VARCHAR(16) NOT NULL,          -- requirement | design | test
  domain        VARCHAR(32) NOT NULL,
  title         VARCHAR(255) NOT NULL,
  status        VARCHAR(16) NOT NULL,
  version       INTEGER NOT NULL DEFAULT 1,
  owner         VARCHAR(64) NULL,
  file_path     VARCHAR(512) NOT NULL,
  content_sha256 CHAR(64) NOT NULL,
  created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ(3) NULL,
  CONSTRAINT uniq_spec_doc_file UNIQUE (file_path)
);
CREATE INDEX IF NOT EXISTS idx_spec_documents_doc_id ON spec_documents (doc_id, version);

-- spec_items：条目级索引，ref 为全局引用（<DOC-ID>#<ITEM-KEY>）。
CREATE TABLE IF NOT EXISTS spec_items (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_id         VARCHAR(64) NOT NULL,
  doc_version    INTEGER NOT NULL DEFAULT 1,
  item_key       VARCHAR(16) NOT NULL,         -- REQ-01 | DEC-02
  item_type      VARCHAR(8) NOT NULL,          -- REQ | NFR | AC | ASM | DEC
  ref            VARCHAR(128) NOT NULL,        -- 全局引用，grep-able
  title          VARCHAR(255) NOT NULL,
  body           TEXT NULL,
  line_no        INTEGER NOT NULL DEFAULT 0,
  content_sha256 CHAR(64) NULL,
  created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_spec_item_ref UNIQUE (ref)
);
CREATE INDEX IF NOT EXISTS idx_spec_items_doc ON spec_items (doc_id);

-- cases：用例（source_ref 指向 TEST yaml 中的 TC-xx，与 ZTF 同构）。
CREATE TABLE IF NOT EXISTS cases (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(255) NOT NULL,
  source_ref  VARCHAR(512) NOT NULL,
  source_hash CHAR(64) NOT NULL,
  suite       VARCHAR(64) NULL,
  automation  VARCHAR(16) NULL,
  priority    VARCHAR(4) NULL,
  spec_doc_id VARCHAR(64) NULL,
  created_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at  TIMESTAMPTZ(3) NULL,
  CONSTRAINT uniq_cases_source_ref UNIQUE (source_ref)
);

-- case_steps：用例步骤；checkPoints 以 JSONB 存于 checks，省一张表（DEC-02）。
CREATE TABLE IF NOT EXISTS case_steps (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id    BIGINT NOT NULL,
  seq        INTEGER NOT NULL,
  name       VARCHAR(512) NOT NULL,
  checks     JSONB NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_case_step_seq UNIQUE (case_id, seq)
);

-- trace_links：追溯链接；唯一键是去重的最终防线（DEC-03）。
CREATE TABLE IF NOT EXISTS trace_links (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type VARCHAR(16) NOT NULL,
  source_ref  VARCHAR(512) NOT NULL,
  link_type   VARCHAR(16) NOT NULL,           -- covers | verifies
  target_type VARCHAR(16) NOT NULL,
  target_ref  VARCHAR(512) NOT NULL,
  strength    SMALLINT NOT NULL DEFAULT 100,
  origin      VARCHAR(16) NOT NULL DEFAULT 'file',  -- file | inference
  created_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_trace_link UNIQUE (source_type, source_ref, link_type, target_type, target_ref)
);
CREATE INDEX IF NOT EXISTS idx_trace_links_target ON trace_links (target_ref);

