-- ---------- 4. 最小权限（与 000010/000019/000020/000021 同一模型） ----------
-- regto_app 需要读写绑定（人类专属动作在应用层拦，DB 层不区分角色）；
-- 仍**不授 DELETE**：解绑是 revoked_at 的软删，物理删除只归 DBA/迁移。
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'regto_app') THEN
        EXECUTE 'REVOKE ALL ON public.roles FROM regto_app';
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON public.roles TO regto_app';
        EXECUTE 'REVOKE ALL ON public.user_roles FROM regto_app';
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON public.user_roles TO regto_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.roles_id_seq TO regto_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.user_roles_id_seq TO regto_app';
    END IF;
END $$;

