-- 执行者：本迁移必须以**超级用户**连接执行（REGTO_MIGRATION_URL）。
-- 方言：PostgreSQL（本机 WSL2）。命名规范见 AGENTS.md §5。
--
-- 注意本迁移**不建**权限矩阵表：5 角色 × 12 资源 × 4 动作 = 240 格的真源在代码
-- （internal/domain/account/matrix.go）。理由见 DESIGN-ACCOUNT-001#DEC-01——
-- 权限规则一旦成为运行时可 UPDATE 的数据，「谁能改权限」就说不清了。
-- 本迁移只建「事实」：角色是什么（roles）、谁有什么角色（user_roles）。

-- ---------- 1. 角色元数据 ----------
CREATE TABLE IF NOT EXISTS roles (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(16) NOT NULL,              -- admin|pm|dev|qa|guest，与领域常量一致
  name        VARCHAR(64) NOT NULL,
  description VARCHAR(255) NOT NULL DEFAULT '',
  builtin     BOOLEAN NOT NULL DEFAULT true,     -- 内置角色不可删（本期也无删除接口）
  created_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uniq_roles_code UNIQUE (code)
);

-- ---------- 2. 用户↔角色绑定（软删，保留「谁在何时有过什么角色」） ----------
CREATE TABLE IF NOT EXISTS user_roles (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id),
  role_id    BIGINT NOT NULL REFERENCES roles(id),
  granted_by BIGINT NULL REFERENCES users(id),   -- 授予人；迁移种子可为空
  granted_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  revoked_at TIMESTAMPTZ(3) NULL                -- 软删：吊销不等于删除历史
);

-- 同一用户同一角色最多一条**活跃**绑定；历史记录（已吊销）不占唯一性。
CREATE UNIQUE INDEX IF NOT EXISTS uniq_user_roles_active
    ON user_roles (user_id, role_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_roles_user ON user_roles (user_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles (role_id) WHERE revoked_at IS NULL;

