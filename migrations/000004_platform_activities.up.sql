-- 依据：ROADMAP §3.3 映射表「横切 4」；AGENTS.md「工作即留痕」
-- 说明：actor_id 用 VARCHAR（人类存 account，AI/SYS 存 agent_id），actor_type 区分 human/ai/system。
--       领域事件（DomainEvent）由 usecase 层异步/同步写入本表；traces（000021）是 SpecDD 增强版。
-- 方言：PostgreSQL（本机 WSL2）。合入 main 后禁止修改。

CREATE TABLE IF NOT EXISTS activities (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_type  VARCHAR(32) NOT NULL,               -- story/task/bug/product/project/...
  object_id    BIGINT NOT NULL,
  product_id   BIGINT NULL,
  project_id   BIGINT NULL,
  actor_type   VARCHAR(16) NOT NULL,               -- human/ai/system
  actor_id     VARCHAR(64) NOT NULL,               -- account 或 agent_id
  action       VARCHAR(64) NOT NULL,               -- opened/edited/transitioned/...
  comment      TEXT NULL,
  extra        JSONB NULL,
  created_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT chk_activities_actor_type CHECK (actor_type IN ('human','ai','system'))
);
CREATE INDEX IF NOT EXISTS idx_activities_object ON activities (object_type, object_id, id);
CREATE INDEX IF NOT EXISTS idx_activities_actor ON activities (actor_type, actor_id, id);
CREATE INDEX IF NOT EXISTS idx_activities_product ON activities (product_id, id) WHERE product_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS activity_changes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activity_id BIGINT NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
  field       VARCHAR(64) NOT NULL,
  old_value   TEXT NULL,
  new_value   TEXT NULL
);
CREATE INDEX IF NOT EXISTS idx_activity_changes_activity ON activity_changes (activity_id);
