  name        VARCHAR(90) NOT NULL,
  product_id  BIGINT NOT NULL,
  project_id  BIGINT NULL,
  build_id    BIGINT NULL,                    -- 预留（M2-B build 域），本期不校验存在性
  type        VARCHAR(32) NOT NULL DEFAULT '',
