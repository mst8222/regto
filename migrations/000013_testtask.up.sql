-- ============================================================
-- 2. 测试单-用例关联（禅道 zt_testrun：锁定 case_version 快照）
-- ============================================================
CREATE TABLE IF NOT EXISTS test_task_cases (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_task_id    BIGINT NOT NULL,
  case_id         BIGINT NOT NULL,
  case_version    SMALLINT NOT NULL DEFAULT 1,   -- 加入时的版本快照（DEC-02）
  assigned_to_id  BIGINT NULL,
  status          VARCHAR(16) NOT NULL DEFAULT 'wait',  -- wait|running|done
  last_run_result VARCHAR(16) NULL,              -- pass|fail|blocked|skip|n/a
  last_run_at     TIMESTAMPTZ(3) NULL,
  created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at      TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_ttc_task ON test_task_cases (test_task_id) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uniq_ttc_task_case
    ON test_task_cases (test_task_id, case_id) WHERE deleted_at IS NULL;

