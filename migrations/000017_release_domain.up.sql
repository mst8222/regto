-- ============================================================
-- 1. 产品计划（禅道 zt_productplan；DEC-01 单表父子计划）
-- ============================================================
CREATE TABLE IF NOT EXISTS plans (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    BIGINT NOT NULL,
  branch_id     BIGINT NULL,
  parent_id     BIGINT NULL,                  -- DEC-01：子计划（0/空=顶层）
  title         VARCHAR(255) NOT NULL,
  status        VARCHAR(16) NOT NULL DEFAULT 'wait',   -- wait|doing|done|closed
  "desc"        TEXT NULL,   -- desc 是 SQL 保留字，必须引号
  begin_date    DATE NULL,   -- begin/end 是 SQL 保留字，与 test_tasks 一致用 _date 后缀
  end_date      DATE NULL,
  finished_at   TIMESTAMPTZ(3) NULL,
  closed_at     TIMESTAMPTZ(3) NULL,
  closed_reason VARCHAR(255) NOT NULL DEFAULT '',
  opened_by_id  BIGINT NOT NULL,
  opened_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_plans_product_status ON plans (product_id, status);
CREATE INDEX IF NOT EXISTS idx_plans_parent ON plans (parent_id) WHERE parent_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_plans_title ON plans (title) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_plans_end_date ON plans (end_date);

-- ============================================================
-- 2. 计划-需求关联（禅道 zt_planstory；DEC-03 关联表 + order）
-- ============================================================
CREATE TABLE IF NOT EXISTS plan_stories (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id    BIGINT NOT NULL,
  story_id   BIGINT NOT NULL,
  "order"    SMALLINT NOT NULL DEFAULT 0,     -- order 是 SQL 保留字，必须引号
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ(3) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_plan_story
    ON plan_stories (plan_id, story_id) WHERE deleted_at IS NULL;   -- AC-03
CREATE INDEX IF NOT EXISTS idx_plan_stories_story ON plan_stories (story_id) WHERE deleted_at IS NULL;

-- ============================================================
-- 3. 发布（禅道 zt_release；DEC-04 关联保留逗号串快照）
-- ============================================================
CREATE TABLE IF NOT EXISTS releases (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     BIGINT NOT NULL,
  branch_id      BIGINT NULL,
  name           VARCHAR(255) NOT NULL,
  system         VARCHAR(16) NOT NULL DEFAULT 'trunk',   -- trunk|branch（REQ-04）
  marker         BOOLEAN NOT NULL DEFAULT false,         -- 里程碑发布
  status         VARCHAR(16) NOT NULL DEFAULT 'wait',    -- wait|normal|fail|terminate
  date           DATE NULL,                              -- 计划发布日期
  released_at    TIMESTAMPTZ(3) NULL,                    -- publish 时记录（REQ-05）
  story_ids      TEXT NOT NULL DEFAULT '',               -- 逗号串快照（DEC-04）
  bug_ids        TEXT NOT NULL DEFAULT '',
  build_ids      TEXT NOT NULL DEFAULT '',
  mailto         TEXT NOT NULL DEFAULT '',               -- NFR-03：只存不发
  notify         VARCHAR(255) NOT NULL DEFAULT '',
  "desc"         TEXT NULL,
  opened_by_id   BIGINT NOT NULL,
  opened_at      TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at     TIMESTAMPTZ(3) NULL
);
CREATE INDEX IF NOT EXISTS idx_releases_product_status ON releases (product_id, status);
CREATE INDEX IF NOT EXISTS idx_releases_name ON releases (name) WHERE deleted_at IS NULL;

-- ============================================================
-- 4. 构建（禅道 zt_build；DEC-06 无状态机 + 构建号产品内唯一）
-- ============================================================
CREATE TABLE IF NOT EXISTS builds (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    BIGINT NOT NULL,
  project_id    BIGINT NULL,                  -- 所属迭代（禅道 execution）
  name          VARCHAR(255) NOT NULL,
  builds        VARCHAR(255) NOT NULL,        -- 构建号（如 1.0.0）
  system        VARCHAR(16) NOT NULL DEFAULT 'trunk',
  scm_path      VARCHAR(255) NOT NULL DEFAULT '',
  file_path     VARCHAR(255) NOT NULL DEFAULT '',
  date          DATE NULL,
  builder       VARCHAR(64) NOT NULL DEFAULT '',
  story_ids     TEXT NOT NULL DEFAULT '',
  bug_ids       TEXT NOT NULL DEFAULT '',
  "desc"        TEXT NULL,
  created_by_id BIGINT NOT NULL,
  created_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at    TIMESTAMPTZ(3) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_builds_product_builds
    ON builds (product_id, builds) WHERE deleted_at IS NULL;   -- AC-04
CREATE INDEX IF NOT EXISTS idx_builds_product_date ON builds (product_id, date);

-- ============================================================
-- 5. 应用账号授权（与 000014 同一模式：显式列举本迁移新表）
-- ============================================================
DO $$
DECLARE
    tbl text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'regto_app') THEN
        RAISE NOTICE '角色 regto_app 不存在，跳过授权（请先执行 docs/deploy/01-init-database.sql）';
        RETURN;
    END IF;

    FOR tbl IN
        SELECT unnest(ARRAY['plans', 'plan_stories', 'releases', 'builds'])
    LOOP
        EXECUTE format('REVOKE ALL ON public.%I FROM regto_app', tbl);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON public.%I TO regto_app', tbl);
        RAISE NOTICE '已授权 regto_app: %', tbl;
    END LOOP;
END
$$;

